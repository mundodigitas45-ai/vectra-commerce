import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const [w] = JSON.parse(fs.readFileSync(process.env.WORKFLOW_CANDIDATE || 'work/n8n-art-director-candidate-sanitized-test.json','utf8'));
const nodes = new Map(w.nodes.map(n=>[n.name,n]));
const link = name => w.connections[name]?.main?.[0]?.[0]?.node;
assert.equal(w.active,false);
assert.equal(link('Usar Fotografia Aprovada?'),'OpenAI - Direção Criativa por Foto');
assert.equal(link('OpenAI - Direção Criativa por Foto'),'Validar Direção e Preparar Fundo');
assert.equal(link('Validar Fundo e Compor Foto Real'),'API - Concluir Imagem');
const source={job:{id:'job'},channel:{id:'channel'},format:{key:'square'},worker_id:'worker',reference_image_url:'https://example.invalid/photo',campaign:{brief:{real_photo_media_id:'photo-id'}}};
const planCode=nodes.get('Validar Direção e Preparar Fundo').parameters.jsCode;
const response={id:'response',usage:{input_tokens:100},output:[{content:[{type:'output_text',text:JSON.stringify({layout:'hero_center',ink:'dark',accent:'yellow',scene:'Ambiente editorial claro com luz lateral suave, textura de papel e espaço central limpo'})}]}]};
const $=()=>({first:()=>({json:source})});
const [{json:planned}]=vm.runInNewContext(`(()=>{${planCode}})()`,{$, $json:response, Date, Error, JSON});
assert.match(planned.generated_background_prompt,/Não desenhe produto/);
assert.equal(planned.openai_background_request.tools[0].type,'image_generation');
assert.equal(planned.visual_plan.layout,'hero_center');
const imageCode=nodes.get('Validar Fundo e Compor Foto Real').parameters.jsCode;
const $image=()=>({first:()=>({json:planned})});
const [{json:completion}]=vm.runInNewContext(`(()=>{${imageCode}})()`,{$:$image,$json:{id:'generated',output:[{type:'image_generation_call',result:'a'.repeat(101)}]},Date,Error,JSON});
assert.equal(completion.metadata.visual_plan.layout,'hero_center');
assert.equal(completion.composition_mode,'professional_real_photo_v1');
assert.equal(completion.reference_image_url,source.reference_image_url);
assert.equal(completion.image_base64.length,101);
console.log('GRAPH_PLAN_IMAGE_COMPLETION_OK=true');
